import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { gitConfig, INSTALLED_MARKER, installScript, pubFiles, sshConfig } from "../src/guest-config.ts";
import type { RepoEntry, StoredKey } from "../src/state.ts";

function key(blob: string, comment: string): StoredKey {
	return { type: "ecdsa-sha2-nistp256", blob, comment, fingerprint: "SHA256:x", registered: true };
}

const repos: Record<string, RepoEntry> = {
	"owner/private": {
		private: true,
		keys: { read: key("AAAAread", "github.com-owner/private-read"), write: key("AAAAwrite", "it's $HOME `x`") },
	},
	"owner/public": { private: false, keys: { write: key("AAAApub", "github.com-owner/public-write") } },
	"owner/readonly": { private: true, keys: { read: key("AAAAro", "") } },
};

/** Run a command with HOME pointing at a sandbox, and return its output. */
function inHome(home: string, command: string, args: string[], input?: string): string {
	return execFileSync(command, args, {
		env: { ...process.env, HOME: home, GIT_CONFIG_NOSYSTEM: "1" },
		input,
		encoding: "utf8",
	}).trim();
}

test("sshConfig has one pinned host block per key", () => {
	const config = sshConfig(repos);
	assert.match(config, /^# Generated by the pi-roost wizard/);
	const hosts = [...config.matchAll(/^Host (\S+)$/gm)].map((match) => match[1]);
	assert.deepEqual(hosts, [
		"gh-read.owner.private",
		"gh-write.owner.private",
		"gh-write.owner.public",
		"gh-read.owner.readonly",
	]);
	assert.match(config, /IdentityFile ~\/\.ssh\/pi-roost\/owner\.private\.write\.pub\n {2}IdentitiesOnly yes/);
	assert.equal((config.match(/IdentitiesOnly yes/g) ?? []).length, 4);
});

test("pubFiles holds one line per key", () => {
	assert.deepEqual(Object.keys(pubFiles(repos)), [
		"owner.private.read.pub",
		"owner.private.write.pub",
		"owner.public.write.pub",
		"owner.readonly.read.pub",
	]);
	assert.equal(pubFiles(repos)["owner.readonly.read.pub"], "ecdsa-sha2-nistp256 AAAAro\n");
});

test("gitConfig rejects a name that is not owner/name", () => {
	assert.throws(() => gitConfig({ 'x"]\n[evil': { keys: { read: key("A", "") } } }), /not a repository name/);
});

test("the install script sets up a guest, and git routes each address to the right key", (t) => {
	const home = mkdtempSync(join(tmpdir(), "pi-roost-guest-"));
	t.after(() => rmSync(home, { recursive: true, force: true }));
	mkdirSync(join(home, ".ssh"));
	const existing = "Host github.com\n  HostName github.com\n  User git\n";
	writeFileSync(join(home, ".ssh", "config"), existing);

	const script = installScript(repos);
	assert.match(inHome(home, "bash", ["-s"], script), new RegExp(INSTALLED_MARKER));
	// A second run must change nothing.
	inHome(home, "bash", ["-s"], script);

	const sshFile = readFileSync(join(home, ".ssh", "config"), "utf8");
	assert.equal(sshFile, `Include ~/.ssh/pi-roost/config\n\n${existing}`);
	assert.equal(readFileSync(join(home, ".ssh", "pi-roost", "config"), "utf8"), sshConfig(repos));
	// A comment with shell characters arrives unchanged.
	assert.equal(
		readFileSync(join(home, ".ssh", "pi-roost", "owner.private.write.pub"), "utf8"),
		"ecdsa-sha2-nistp256 AAAAwrite it's $HOME `x`\n",
	);
	assert.equal(inHome(home, "git", ["config", "--global", "--get-all", "include.path"]), "~/.config/pi-roost/gitconfig");
	assert.match(readFileSync(join(home, ".ssh", "known_hosts"), "utf8"), /^github\.com ssh-ed25519 /);

	// SSH reads the generated blocks as intended.
	const resolved = execFileSync("ssh", ["-F", join(home, ".ssh", "pi-roost", "config"), "-G", "gh-write.owner.private"], {
		encoding: "utf8",
	});
	assert.match(resolved, /^hostname github\.com$/m);
	assert.match(resolved, /^user git$/m);
	assert.match(resolved, /^identitiesonly yes$/m);

	const fetchUrl = (address: string) => inHome(home, "git", ["ls-remote", "--get-url", address]);
	const repo = join(home, "repo");
	inHome(home, "git", ["init", "-q", repo]);
	const pushUrl = (address: string) => {
		inHome(home, "git", ["-C", repo, "remote", "add", "probe", address]);
		const url = inHome(home, "git", ["-C", repo, "remote", "get-url", "--push", "probe"]);
		inHome(home, "git", ["-C", repo, "remote", "remove", "probe"]);
		return url;
	};

	// Private, read and write: fetch with the read key, push with the write key.
	for (const address of [
		"git@github.com:owner/private.git",
		"ssh://git@github.com/owner/private.git",
		"https://github.com/owner/private.git",
	]) {
		assert.equal(fetchUrl(address), "gh-read.owner.private:owner/private.git");
		assert.equal(pushUrl(address), "gh-write.owner.private:owner/private.git");
	}

	// Public with write: fetch needs no key and goes over HTTPS.
	assert.equal(fetchUrl("git@github.com:owner/public.git"), "https://github.com/owner/public.git");
	assert.equal(fetchUrl("https://github.com/owner/public.git"), "https://github.com/owner/public.git");
	assert.equal(pushUrl("https://github.com/owner/public.git"), "gh-write.owner.public:owner/public.git");
	assert.equal(pushUrl("git@github.com:owner/public.git"), "gh-write.owner.public:owner/public.git");

	// Private, read only: a push is not sent to any write key.
	assert.equal(fetchUrl("git@github.com:owner/readonly.git"), "gh-read.owner.readonly:owner/readonly.git");
	assert.equal(pushUrl("git@github.com:owner/readonly.git"), "gh-read.owner.readonly:owner/readonly.git");

	// A repository whose name merely starts the same is left alone.
	assert.equal(fetchUrl("git@github.com:owner/private-other.git"), "git@github.com:owner/private-other.git");
	assert.equal(fetchUrl("https://github.com/owner/public-other.git"), "https://github.com/owner/public-other.git");
	// So is an address without the .git suffix.
	assert.equal(fetchUrl("https://github.com/owner/private"), "https://github.com/owner/private");
});

test("the install script removes public keys that are no longer recorded", (t) => {
	const home = mkdtempSync(join(tmpdir(), "pi-roost-guest-"));
	t.after(() => rmSync(home, { recursive: true, force: true }));
	inHome(home, "bash", ["-s"], installScript(repos));
	inHome(home, "bash", ["-s"], installScript({ "owner/public": repos["owner/public"] as RepoEntry }));
	const left = inHome(home, "ls", [join(home, ".ssh", "pi-roost")]).split("\n");
	assert.deepEqual(left, ["config", "owner.public.write.pub"]);
});
